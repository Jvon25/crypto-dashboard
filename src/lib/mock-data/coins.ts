// ─── Data Access Functions ──────────────────────────────────────────────────

export function getCoins(): Coin[] {
  return mockCoins.map((coin) => ({ ...coin }));
}

export function getCoinBySymbol(symbol: string, source: Coin[] = mockCoins): Coin | undefined {
  return source.find((c) => c.symbol === symbol);
}

export function getTrendingCoins(): Coin[] {
  return mockCoins.filter(
    (c) => c.volumeLevel === 'VERY_HIGH' || c.volumeLevel === 'HIGH' || Math.abs(c.change24h) > 5
  );
}

export function getBullishCoins(): Coin[] {
  return mockCoins.filter((c) => c.status === 'BULLISH_CONDITIONS');
}

export function getBearishCoins(): Coin[] {
  return mockCoins.filter((c) => c.status === 'BEARISH_CONDITIONS');
}

export function getHighRiskCoins(): Coin[] {
  return mockCoins.filter(
    (c) => c.riskLevel === 'HIGH' || c.riskLevel === 'CRITICAL' || c.status === 'HIGH_RISK' || c.status === 'ELEVATED_RISK'
  );
}

export function filterCoins(filters: {
  trend?: 'ALL' | string;
  trend4h?: 'ALL' | Trend;
  trend1h?: 'ALL' | Trend;
  rsi?: 'ALL' | 'ABOVE_50' | 'BELOW_50';
  divergence?: 'ALL' | DivergenceType;
  risk?: 'ALL' | RiskLevel;
}): Coin[] {
  return mockCoins.filter((coin) => {
    if (filters.trend && filters.trend !== 'ALL') {
      if (filters.trend === 'BULLISH' && coin.status !== 'BULLISH_CONDITIONS') return false;
      if (filters.trend === 'BEARISH' && coin.status !== 'BEARISH_CONDITIONS') return false;
      if (filters.trend === 'NEUTRAL' && coin.status !== 'NEUTRAL') return false;
    }
    if (filters.trend4h && filters.trend4h !== 'ALL' && coin.trend4h !== filters.trend4h) return false;
    if (filters.trend1h && filters.trend1h !== 'ALL' && coin.trend1h !== filters.trend1h) return false;
    if (filters.rsi && filters.rsi !== 'ALL') {
      if (filters.rsi === 'ABOVE_50' && coin.rsi4h < 50) return false;
      if (filters.rsi === 'BELOW_50' && coin.rsi4h >= 50) return false;
    }
    if (filters.divergence && filters.divergence !== 'ALL') {
      if (coin.divergence4h !== filters.divergence && coin.divergence1h !== filters.divergence) return false;
    }
    if (filters.risk && filters.risk !== 'ALL' && coin.riskLevel !== filters.risk) return false;
    return true;
  });
}
